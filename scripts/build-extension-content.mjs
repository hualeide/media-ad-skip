function formatBrandArray(arr) {
  const lines = [];
  for (let i = 0; i < arr.length; i += 7) {
    lines.push(`    ${arr.slice(i, i + 7).map((x) => JSON.stringify(x)).join(', ')},`);
  }
  return `[\n${lines.join('\n')}\n  ]`;
}

/** 同步品牌表到油猴源（BRAND_KW_START/END）与 extension/shared/config.js */
function syncSharedConfig() {
  const brandLit = formatBrandArray(DEFAULT_BRAND_KW);
  const userPath = path.join(root, 'media-ad-skip.user.js');
  let user = fs.readFileSync(userPath, 'utf8').replace(/\r\n/g, '\n');
  const block = `/* BRAND_KW_START */\n  const DEFAULT_BRAND_KW = ${brandLit};\n  /* BRAND_KW_END */`;
  const re = /\/\*\s*BRAND_KW_START\s*\*\/[\s\S]*?\/\*\s*BRAND_KW_END\s*\*\//;
  if (!re.test(user)) {
    console.warn('warn: BRAND_KW markers not found in userscript');
  } else {
    user = user.replace(re, block);
    fs.writeFileSync(userPath, user);
  }

  const sharedDir = path.join(root, 'extension', 'shared');
  fs.mkdirSync(sharedDir, { recursive: true });
  fs.writeFileSync(
    path.join(sharedDir, 'config.js'),
    `/* auto-generated from src/config.mjs — do not edit by hand */\n`
      + `var MAS_DEFAULT_BRAND_KW = ${JSON.stringify(DEFAULT_BRAND_KW, null, 2)};\n`,
  );
}


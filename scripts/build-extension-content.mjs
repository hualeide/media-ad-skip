/**
 * 从 media-ad-skip.user.js 生成 extension/content/content.js
 * 油猴里的 cfg/storage/面板增强 helpers 会被头文件替换；检测逻辑保留。
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
let body = fs.readFileSync(path.join(root, 'media-ad-skip.user.js'), 'utf8').replace(/\r\n/g, '\n');
body = body.replace(/^\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\s*/, '');
body = body.replace(/^\(function \(\) \{\s*'use strict';\s*/, '');
body = body.replace(/\}\)\(\);\s*$/, '');

const adStart = body.indexOf('  const AD_START');
if (adStart < 0) throw new Error('AD_START not found');
body = body.slice(adStart);

// 去掉油猴 cfg/state/helpers/storage（扩展头已提供同等实现）
body = body.replace(
  /\n  \/\*\* @type \{typeof DEFAULTS\} \*\/\n  let cfg = loadCfg\(\);[\s\S]*?\/\/ -------------------- utils --------------------\n/,
  '\n  // -------------------- utils --------------------\n',
);

body = body.replace(/  const AD_GENERAL = \[[^\]]+\];\n/, '  /* AD_GENERAL → generalKw() */\n');
body = body.replace(/AD_BRAND_KW\.filter/g, 'brandList().filter');
body = body.replace(/AD_GENERAL\.some/g, 'generalKw().some');

body = body.replace(
  /const data = await gmFetchJson\(url\);\n      if \(!Array\.isArray\(data\)\) return \[\];/,
  'const data = await proxyFetchJson(url);\n      if (!Array.isArray(data)) return [];',
);

// 仅当仍是同步 boot 时改写
if (body.includes('function boot() {')) {
  body = body.replace(
    `function boot() {
    bindExtCommands();
    ensureToastStyles();
    ensurePanel();
    registerMenu();
    watchPlayback();`,
    `async function boot() {
    bindExtCommands();
    cfg = await loadCfgAsync();
    if (IS_EXT && chrome.storage?.onChanged) {
      chrome.storage.onChanged.addListener((changes, area) => {
        if (area === 'sync' && changes.cfg) {
          const prevFeed = cfg.feedPollMs;
          cfg = { ...cfg, ...changes.cfg.newValue };
          if (cfg.showPanel) ensurePanel();
          else hidePanel();
          if (prevFeed !== cfg.feedPollMs) startFeedPoll();
        }
        if (area === 'local') {
          if (changes.brandKeywords) cfg.brandKeywords = changes.brandKeywords.newValue;
          if (changes.blockBvids) cfg.blockBvids = changes.blockBvids.newValue;
          if (changes.blockMids) cfg.blockMids = changes.blockMids.newValue;
        }
      });
    }
    ensureToastStyles();
    ensurePanel();
    registerMenu();
    watchPlayback();`,
  );
}

const header = `/* Media Ad Skip — extension content (generated by scripts/build-extension-content.mjs) */
(function () {
  'use strict';
  if (window.__MAS_VER__ === '1.5.29') return;
  window.__MAS_VER__ = '1.5.29';

  const IS_EXT = typeof chrome !== 'undefined' && !!(chrome.runtime && chrome.runtime.id);
  const HOST = location.hostname;
  const IS_BILI = HOST.includes('bilibili.com');
  const IS_DOUYIN = HOST.includes('douyin.com');
  if (!IS_BILI && !IS_DOUYIN) return;
  window.__MAS_LOADED__ = true;

  const DEFAULT_BRAND_KW = [
    '转转', '爱回收', '闲鱼', '瓜子', '萤石', '山楂树下', '真我',
    '神奇小鹿', '小鹿冰被', '躺岛', '蓝盒子', '半日闲', '时光存折', '栖作', '甜秘密',
    '华味坊', '酸汤面叶', '劲仔', '卫龙', '盐津铺子', '三只松鼠', '良品铺子', '王小卤', '认养一头牛',
    '妙界', '赫恩', '海洋至尊', '溪木源', '博乐达', '蜜丝婷',
    '盖世小鸡', '飞智', '北通', '黑白调', '骁骑',
    '瑞幸', '安克', '酷态科',
  ];
  const DEFAULTS = {
    autoSkip: true,
    showPanel: false,
    douyinFeedAd: true,
    douyinFeedLive: false,
    douyinFeedShop: true,
    douyinInVideo: true,
    biliInVideo: true,
    feedPollMs: 700,
    countdownSec: 3,
    softOralSkipSec: 35,
    useSponsorBlock: true,
    showUndoToast: true,
    brandKeywords: DEFAULT_BRAND_KW.slice(),
    blockBvids: [],
    blockMids: [],
  };

  let cfg = { ...DEFAULTS };
  let panelEl = null;
  let statusText = '待命';
  let activeSeg = null;
  let activeSegs = [];
  let skippedKeys = new Set();
  let lastKey = '';
  let lastSkip = null;
  let softOralReady = false;

  function brandList() {
    if (!Array.isArray(cfg.brandKeywords)) return DEFAULT_BRAND_KW.slice();
    const cur = cfg.brandKeywords.map((x) => String(x).trim()).filter(Boolean);
    if (!cur.length) return [];
    if (cur.length < Math.ceil(DEFAULT_BRAND_KW.length * 0.5)) {
      const set = new Set(cur);
      for (const k of DEFAULT_BRAND_KW) set.add(k);
      return [...set];
    }
    return cur;
  }

  function generalKw() {
    return ['已买', '购买', '购入', '接广', '广告', '广子', '感谢金主', '商单', '恰饭', '下单', '买买买', ...brandList()];
  }

  function currentVideoId() {
    if (IS_BILI) {
      const m = location.pathname.match(/\\/video\\/(BV[\\w]+)/i);
      return m ? m[1] : null;
    }
    if (IS_DOUYIN) {
      if (typeof getDouyinAwemeId === 'function') return getDouyinAwemeId();
      const m = location.pathname.match(/\\/video\\/(\\d+)/);
      return m ? m[1] : null;
    }
    return null;
  }

  function isBlockedVideo() {
    const id = currentVideoId();
    if (!id) return false;
    return (cfg.blockBvids || []).map(String).includes(String(id));
  }

  function isBlockedUp(mid) {
    if (mid == null || mid === '') return false;
    return (cfg.blockMids || []).map(String).includes(String(mid));
  }

  async function appendFeedback(entry) {
    const item = {
      at: Date.now(),
      href: location.href,
      videoId: currentVideoId(),
      ...entry,
    };
    try {
      if (IS_EXT && chrome.storage?.local) {
        const { feedbackLog = [] } = await chrome.storage.local.get(['feedbackLog']);
        await chrome.storage.local.set({ feedbackLog: [...feedbackLog, item].slice(-50) });
      } else {
        const raw = localStorage.getItem('mas-feedback') || '[]';
        const arr = JSON.parse(raw);
        arr.push(item);
        localStorage.setItem('mas-feedback', JSON.stringify(arr.slice(-50)));
      }
    } catch (e) {
      console.log('[MAS] feedback save fail', e);
    }
    return item;
  }

  async function reportWrongMark() {
    const seg = lastSkip?.seg || activeSeg;
    const item = await appendFeedback({
      reason: 'wrong_skip',
      seg: seg ? { start: seg.start, end: seg.end, source: seg.source } : null,
      fromTime: lastSkip?.fromTime ?? null,
    });
    if (lastSkip) undoLastSkip();
    else if (seg) skippedKeys.add(segKey(seg));
    const text = JSON.stringify(item, null, 2);
    try {
      await navigator.clipboard.writeText(text);
      setStatus('已记录标错并复制到剪贴板');
    } catch {
      setStatus('已记录标错（复制失败，见设置页导出）');
    }
  }

  function blockCurrentVideo(forcedId) {
    const id = forcedId || currentVideoId();
    if (!id) {
      setStatus('无法识别视频 ID');
      return false;
    }
    const set = new Set((cfg.blockBvids || []).map(String));
    set.add(String(id));
    cfg.blockBvids = [...set];
    saveCfg();
    activeSeg = null;
    activeSegs = [];
    skippedKeys = new Set();
    lastSkip = null;
    setStatus('本视频已禁用跳过');
    return true;
  }

  function unblockCurrentVideo(forcedId) {
    const id = forcedId || currentVideoId();
    if (!id) {
      setStatus('无法识别视频 ID');
      return false;
    }
    cfg.blockBvids = (cfg.blockBvids || []).map(String).filter((x) => x !== String(id));
    saveCfg();
    setStatus('已恢复本集跳过');
    return true;
  }

  function isCurrentVideoBlocked() {
    const id = currentVideoId();
    if (!id) return false;
    return (cfg.blockBvids || []).map(String).includes(String(id));
  }

  function undoLastSkip() {
    if (!lastSkip) {
      setStatus('无可撤销跳过');
      return;
    }
    if (seekTo(lastSkip.fromTime)) {
      skippedKeys.delete(lastSkip.key);
      setStatus('已撤销 → ' + formatTime(lastSkip.fromTime));
      lastSkip = null;
      hideUndoToast();
    }
  }

  function hideUndoToast() {
    dismissMasToast(document.getElementById('mas-undo-toast'));
  }

  function dismissMasToast(el) {
    if (!el) return;
    clearTimeout(el._hideAnim);
    el.style.display = 'none';
  }

  function ensureToastStyles() {
    if (document.getElementById('mas-toast-style')) return;
    const style = document.createElement('style');
    style.id = 'mas-toast-style';
    style.textContent = ''
      + '#mas-undo-toast,#mas-skip-toast{'
      + 'position:fixed;right:20px;bottom:24px;z-index:2147483646;'
      + 'padding:12px 14px;border-radius:12px;'
      + 'font:600 13px/1.35 -apple-system,BlinkMacSystemFont,"Segoe UI","PingFang SC",sans-serif;'
      + 'color:#f5f5f7;display:none;'
      + 'max-width:min(300px,calc(100vw - 40px));'
      + 'background:#1c1c1e;border:1px solid #3a3a3c;'
      + 'box-shadow:0 8px 24px rgba(0,0,0,.35)}'
      + '#mas-undo-toast .mas-toast-title,#mas-skip-toast .mas-toast-title{font-weight:600}'
      + '#mas-undo-toast .mas-toast-sub,#mas-skip-toast .mas-toast-sub{margin-top:4px;font-weight:500;font-size:12px;opacity:.78}'
      + '#mas-undo-toast .mas-toast-actions,#mas-skip-toast .mas-toast-actions{margin-top:10px;display:flex;gap:8px;flex-wrap:wrap}'
      + '#mas-undo-toast .mas-btn,#mas-skip-toast .mas-btn{appearance:none;-webkit-appearance:none;cursor:pointer;border:0;border-radius:8px;padding:6px 12px;font:600 12px/1.2 inherit}'
      + '#mas-undo-toast .mas-btn-primary,#mas-skip-toast .mas-btn-primary{background:#0a84ff;color:#fff}'
      + '#mas-undo-toast .mas-btn-ghost,#mas-skip-toast .mas-btn-ghost{background:#2c2c2e;color:#f5f5f7;border:1px solid #3a3a3c}';
    (document.head || document.documentElement).appendChild(style);
  }

  function revealToast(toast) {
    ensureToastStyles();
    toast.style.display = 'block';
  }

  function showUpcomingToast(seg, opts) {
    opts = opts || {};
    if (!seg || cfg.showUndoToast === false) return;
    ensureToastStyles();
    dismissMasToast(document.getElementById('mas-undo-toast'));
    let toast = document.getElementById('mas-skip-toast');
    if (!toast) {
      toast = document.createElement('div');
      toast.id = 'mas-skip-toast';
      document.documentElement.appendChild(toast);
    }
    const range = formatTime(seg.start) + ' → ' + formatTime(seg.end);
    const label = seg.label ? (' · ' + seg.label) : '';
    const withActions = !!opts.withActions;
    toast.innerHTML = '<div class="mas-toast-title">即将跳过广告</div>'
      + '<div class="mas-toast-sub">' + range + label + '</div>'
      + (withActions
        ? '<div class="mas-toast-actions">'
          + '<button type="button" id="mas-toast-go" class="mas-btn mas-btn-primary">立即跳过</button>'
          + '<button type="button" id="mas-toast-no" class="mas-btn mas-btn-ghost">忽略</button></div>'
        : '');
    revealToast(toast);
    if (withActions) {
      toast.querySelector('#mas-toast-go').onclick = () => { doSkip(seg, true); dismissMasToast(toast); };
      toast.querySelector('#mas-toast-no').onclick = () => {
        dismissMasToast(toast);
        skippedKeys.add(segKey(seg));
      };
    }
    clearTimeout(showUpcomingToast._t);
    showUpcomingToast._t = setTimeout(
      () => dismissMasToast(toast),
      withActions ? Math.max(3, cfg.countdownSec || 3) * 1000 : 1800,
    );
  }

  function showUndoToast() {
    if (!cfg.showUndoToast || !lastSkip) return;
    ensureToastStyles();
    dismissMasToast(document.getElementById('mas-skip-toast'));
    let toast = document.getElementById('mas-undo-toast');
    if (!toast) {
      toast = document.createElement('div');
      toast.id = 'mas-undo-toast';
      document.documentElement.appendChild(toast);
    }
    const end = lastSkip.seg ? formatTime(lastSkip.seg.end) : formatTime(lastSkip.toTime);
    toast.innerHTML = '<div class="mas-toast-title">已跳过广告</div>'
      + '<div class="mas-toast-sub">跳到 ' + end + '</div>'
      + '<div class="mas-toast-actions">'
      + '<button type="button" id="mas-undo-btn" class="mas-btn mas-btn-primary">撤销</button>'
      + '<button type="button" id="mas-block-btn" class="mas-btn mas-btn-ghost">本集不跳</button>'
      + '<button type="button" id="mas-wrong-btn" class="mas-btn mas-btn-ghost">标错了</button></div>';
    revealToast(toast);
    toast.querySelector('#mas-undo-btn').onclick = () => undoLastSkip();
    toast.querySelector('#mas-block-btn').onclick = () => {
      blockCurrentVideo();
      dismissMasToast(toast);
    };
    toast.querySelector('#mas-wrong-btn').onclick = () => {
      reportWrongMark();
      dismissMasToast(toast);
    };
    clearTimeout(showUndoToast._t);
    showUndoToast._t = setTimeout(() => dismissMasToast(toast), Math.max(3, cfg.countdownSec || 3) * 1000);
  }

  async function loadCfgAsync() {
    if (IS_EXT && chrome.storage && chrome.storage.sync) {
      const data = await chrome.storage.sync.get(['cfg']);
      let extra = {};
      try {
        extra = await chrome.storage.local.get(['brandKeywords', 'blockBvids', 'blockMids']);
      } catch {}
      const parsed = data.cfg || {};
      let brands = extra.brandKeywords || parsed.brandKeywords || DEFAULTS.brandKeywords;
      if (Array.isArray(brands) && brands.length > 0
        && brands.length < Math.ceil(DEFAULT_BRAND_KW.length * 0.5)) {
        const set = new Set(brands.map((x) => String(x).trim()).filter(Boolean));
        for (const k of DEFAULT_BRAND_KW) set.add(k);
        brands = [...set];
        try { chrome.storage.local.set({ brandKeywords: brands }); } catch {}
      }
      return {
        ...DEFAULTS,
        ...parsed,
        brandKeywords: brands,
        blockBvids: extra.blockBvids || parsed.blockBvids || [],
        blockMids: extra.blockMids || parsed.blockMids || [],
      };
    }
    try {
      const raw = localStorage.getItem('mas-cfg');
      return { ...DEFAULTS, ...(raw ? JSON.parse(raw) : {}) };
    } catch {
      return { ...DEFAULTS };
    }
  }

  function saveCfg() {
    if (IS_EXT && chrome.storage) {
      const syncCfg = { ...cfg };
      const brands = syncCfg.brandKeywords;
      const blocks = syncCfg.blockBvids;
      const mids = syncCfg.blockMids;
      delete syncCfg.brandKeywords;
      delete syncCfg.blockBvids;
      delete syncCfg.blockMids;
      chrome.storage.sync.set({ cfg: syncCfg });
      chrome.storage.local.set({ brandKeywords: brands, blockBvids: blocks, blockMids: mids });
      return;
    }
    localStorage.setItem('mas-cfg', JSON.stringify(cfg));
  }

  function proxyFetchJson(url) {
    if (IS_EXT && chrome.runtime && chrome.runtime.sendMessage) {
      return new Promise((resolve, reject) => {
        chrome.runtime.sendMessage({ type: 'MAS_FETCH', url }, (res) => {
          if (chrome.runtime.lastError) return reject(chrome.runtime.lastError);
          if (!res || !res.ok) return reject(new Error((res && res.error) || 'fetch fail'));
          resolve(res.data);
        });
      });
    }
    return gmFetchJson(url);
  }

`;

